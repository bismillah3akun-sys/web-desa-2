router.get('/admin/rutilahu/:id', requireAuth, asyncHandler(rutilahuController.getDetail))
router.post('/admin/rutilahu', requireAuth, rutilahuSubmissionUpload.fields([{ name: 'photo', maxCount: 1 }, { name: 'identity', maxCount: 1 }, { name: 'referral', maxCount: 1 }, { name: 'ownership', maxCount: 1 }]), asyncHandler(rutilahuController.create))
router.put('/admin/rutilahu/:id', requireAuth, rutilahuSubmissionUpload.fields([{ name: 'photo', maxCount: 1 }]), asyncHandler(rutilahuController.update))
router.delete('/admin/rutilahu/:id', requireAuth, asyncHandler(rutilahuController.remove))
router.get('/admin/rutilahu/:id/photo', requireAuth, asyncHandler(rutilahuController.getPhoto))
router.get('/admin/rutilahu/:id/documents/:kind', requireAuth, asyncHandler(rutilahuController.getDocument))
router.put('/admin/profile', requireAuth, siteImageUpload.fields([{name:'home_hero_image',maxCount:1},{name:'lurah_photo',maxCount:1},{name:'login_background_image',maxCount:1},{name:'government_hero_image',maxCount:1},{name:'potential_hero_image',maxCount:1},{name:'profile_map_image',maxCount:1}]), asyncHandler(adminContentController.updateProfile))
router.put('/admin/demographics', requireAuth, asyncHandler(adminContentController.updateDemographics))
