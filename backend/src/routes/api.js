router.put('/admin/potentials/:id', requireAuth, siteImageUpload.single('image'), asyncHandler(potentialAdminController.update))
router.delete('/admin/potentials/:id', requireAuth, asyncHandler(potentialAdminController.remove))
router.get('/admin/applications', requireAuth, asyncHandler(applicationController.getApplications))
