router.post('/contact', asyncHandler(submissionController.submitContact))
router.post('/guestbook', asyncHandler(submissionController.submitGuestbook))

router.post('/auth/login', asyncHandler(authController.login))
router.get('/auth/me', requireAuth, authController.me)
router.post('/auth/logout', authController.logout)

router.use('/admin', requireAuth, (req, _res, next) => {
  if (req.admin.role === 'rw' && !req.path.startsWith('/rutilahu') && req.path !== '/dashboard') {
    const AppError = require('../utils/AppError')
    return next(new AppError('Akun RW hanya dapat mengakses pengajuan RUTILAHU miliknya', 403))
  }
  return next()
})
router.get('/admin/dashboard', requireAuth, asyncHandler(dashboardController.getDashboard))
router.get('/admin/accounts/rw', requireSuperAdmin, asyncHandler(accountController.list))
router.post('/admin/accounts/rw', requireSuperAdmin, asyncHandler(accountController.create))
router.put('/admin/accounts/rw/:id', requireSuperAdmin, asyncHandler(accountController.update))
router.get('/admin/rutilahu', requireAuth, asyncHandler(rutilahuController.getAdminList))
router.get('/admin/rutilahu/export.xlsx', requireAuth, asyncHandler(rutilahuController.exportExcel))
